// Global autonomous selection variable (defaults to RightSide match routine)
AutonSelection g_selected_auton = AutonSelection::RightSide;

// Global flag tracking whether IMU calibration timed out during pre_auton()
bool g_imu_calibration_failed = false;

// Set these labels before each research condition and use the same values in your logbook.
static const char* telemetry_experiment = "tracking";
static const char* telemetry_condition = "unspecified";

// Re-initializes and tares motor encoders, tracking wheels, and odometry pose
void reset_odometry_and_sensors()
{
	left_front.resetPosition();                                    // Tare front-left drive motor encoder
	left_rear.resetPosition();                                     // Tare rear-left drive motor encoder
	right_front.resetPosition();                                   // Tare front-right drive motor encoder
	right_rear.resetPosition();                                    // Tare rear-right drive motor encoder

	tracking_parallel.resetPosition();                             // Tare forward tracking wheel rotation sensor
	tracking_perp.resetPosition();                                 // Tare lateral tracking wheel rotation sensor
	imu.resetRotation();                                           // Zero inertial sensor rotation angle

	const double kDegToRad = 3.14159265358979323846 / 180.0;       // Conversion factor from degrees to radians
	const double mm_per_deg = tuning.tracking_wheel_circ_mm() / 360.0; // Distance per tracking wheel degree in mm

	OdometryMeasurement init_meas = {                              // Construct initial odometry measurement packet
		average_left_mm(),                                         // Average left chassis linear travel in mm
		average_right_mm(),                                        // Average right chassis linear travel in mm
		tracking_parallel.position(degrees) * mm_per_deg,          // Forward tracking wheel linear travel in mm
		tuning.use_horizontal_tracking_wheel                       // Lateral tracking wheel travel in mm if enabled
			? tracking_perp.position(degrees) * mm_per_deg : 0.0,
		imu.rotation(degrees) * kDegToRad,                         // Current inertial heading in radians
		imu.gyroRate(zaxis, dps) * kDegToRad                       // Current angular turn rate in rad/s
	};

	g_odometry.Reset(init_meas, 0.0);                              // Reset global odometry estimator to origin (0, 0, 0)
}

