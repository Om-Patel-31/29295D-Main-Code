// Routine 3: Programming Skills Autonomous (Skills)
void Skills()
{
	drive(-14.0, 70.0);                                            // Reverse 14 inches at 70% speed to score alliance stake
	drive(8.0);                                                    // Drive forward 8 inches away from stake

	turn(90.0);                                                    // Turn right 90 degrees toward first mobile goal
	drive(-26.0, 75.0);                                            // Reverse 26 inches at 75% speed to clamp mobile goal

	turn_to(0.0);                                                  // Face 0 degrees absolute heading
	drive(30.0);                                                   // Drive forward 30 inches through field rings
	bdrive(36.0, 18.0, 90.0);                                      // Bezier curve 36 in fwd, 18 in right, end facing 90 deg

	drive(20.0);                                                   // Drive forward 20 inches to corral corner rings
	turn_to(180.0);                                                // Turn around to face 180 degrees
	drive(-16.0, 60.0);                                            // Back into corner to place mobile goal
	sdrive();                                                      // Stop and brake drivetrain
}

// Master autonomous entry point called by the VEX Competition system
void autonomous()
{
	if (g_imu_calibration_failed) {                                // Check if inertial sensor calibration failed
		Brain.Screen.clearScreen();                                // Clear Brain display
		Brain.Screen.setPenColor(color(255, 0, 0));                // Set warning text color to red
		Brain.Screen.printAt(20, 120, "ABORT: IMU Calibration Failed"); // Display abort message on screen
		return;                                                    // Abort autonomous if gyro is unreliable
	}

	reset_odometry_and_sensors();                                  // Reset and tare odometry and encoders before starting

	const char* routine = g_selected_auton == AutonSelection::LeftSide ? "LS" :
						  g_selected_auton == AutonSelection::Skills ? "Skills" : "RS";
	const bool telemetry_started =
		TelemetryBegin(telemetry_experiment, telemetry_condition, routine);
	if (telemetry_started) {
		Brain.Screen.printAt(10, 200, true, "CSV logging: %s", TelemetryFilename());
	} else {
		Brain.Screen.printAt(10, 200, "CSV logger unavailable (check SD card)");
	}

	switch (g_selected_auton) {                                    // Dispatch to selected autonomous routine
		case AutonSelection::LeftSide:                             // User selected Left Side
			LS();                                                  // Execute Left Side routine
			break;                                                 // Finish dispatch

		case AutonSelection::Skills:                               // User selected Skills
			Skills();                                              // Execute Skills routine
			break;                                                 // Finish dispatch

		case AutonSelection::RightSide:                            // User selected Right Side
		case AutonSelection::None:                                 // Default fallback
		default:                                                   // Unrecognized selection
			RS();                                                  // Execute Right Side routine
			break;                                                 // Finish dispatch
	}

	sdrive();                                                      // Ensure motors are safely braked upon routine exit
	TelemetryEnd();                                                // Flush buffered data to the CSV file
	if (telemetry_started && !TelemetryHealthy()) {
		Brain.Screen.printAt(10, 220, "CSV write failed");
	}
}
